#pragma once

#include <unordered_set>

#include "core/capture_session.h"
#include "core/input_codes.h"

namespace pskb {

// Pseudo-code for the mouse wheel, so it shares the InputCode space with keys and buttons.
inline constexpr InputCode kMouseWheel = 0x106;

// Facts about one low-level hook event, gathered by the Windows layer.
struct GateEvent {
    bool keyboard = true;   // false for mouse buttons and the wheel
    bool down = true;       // wheel events are always reported as down
    InputCode code = 0;     // virtual key, mouse button, or kMouseWheel
    bool altHeld = false;
    bool winHeld = false;
    bool ctrlHeld = false;
    bool injected = false;  // generated by other software; never swallowed
    bool reserved = false;  // the capture hotkey; always passes so the user can toggle off
    bool mapped = false;    // a key bound to a pad action (mouse buttons and wheel ignore this)
};

// True when the hook must consume the event so the approved window never sees it.
//
// Swallowing happens only while capture is Active and the approved window has focus. Win,
// Alt, and Ctrl+Esc combinations always pass, so Alt+Tab, Win shortcuts, and Task Manager keep
// working. Ctrl+Alt+Del is handled by the kernel and never reaches a hook. Esc is swallowed
// while Active so that it cannot close a Veyra menu or leave fullscreen; the bridge uses it to
// disarm.
bool ShouldSwallow(const GateEvent& event, CaptureMode mode, bool approvedFocused) noexcept;

// Keeps the swallowed presses so that their releases are swallowed too. A release that was not
// swallowed (its press happened before capture became Active) is passed through.
class SwallowedKeys {
public:
    void Remember(InputCode code) { held_.insert(code); }
    // True when the press with this code was swallowed; forgets it.
    bool Consume(InputCode code) { return held_.erase(code) != 0; }
    void Clear() { held_.clear(); }
    bool Empty() const noexcept { return held_.empty(); }

private:
    std::unordered_set<InputCode> held_;
};

}  // namespace pskb
